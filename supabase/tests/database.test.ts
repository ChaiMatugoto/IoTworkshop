import test from 'node:test';
import assert from 'node:assert/strict';
import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
// Executes production SQL in PostgreSQL/WASM. Auth and crypt are test doubles;
// Supabase Auth, bcrypt and Realtime require an actual configured project.
test('database enforces ownership, codes, rate limits, idempotency, totals and reset',async()=>{
 const db=new PGlite();
 try {
 await db.exec(`create role anon; create role authenticated; create schema auth; create schema extensions;
 create table auth.users(id uuid primary key);
 create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
 create function auth.jwt() returns jsonb language sql as $$select jsonb_build_object('is_anonymous',coalesce(current_setting('test.anonymous',true),'true')::boolean)$$;
 create function extensions.gen_salt(text,integer) returns text language sql as $$select 'salt'::text$$;
 create function extensions.crypt(text,text) returns text language sql as $$select $1$$;
 grant usage on schema public,auth to authenticated;
 insert into auth.users values('00000000-0000-0000-0000-000000000001'),('00000000-0000-0000-0000-000000000002'),('00000000-0000-0000-0000-000000000003');`);
 let sql=readFileSync(new URL('../migrations/001_workshop.sql',import.meta.url),'utf8');
 sql=sql.replace('create extension if not exists pgcrypto with schema extensions;','').replace(/do \$\$ begin[\s\S]*?end \$\$;/,'');
 await db.exec(sql);
 await db.exec(readFileSync(new URL('../migrations/002_admin_reset.sql',import.meta.url),'utf8'));
 await db.exec(readFileSync(new URL('../migrations/003_no_join_code.sql',import.meta.url),'utf8'));
 const event='10000000-0000-0000-0000-000000000001';
 await db.exec(`insert into private.map_events(id,name,join_hash) values('${event}','Test','JOIN');
 insert into public.map_tasks values('a','A',1,10),('b','B',2,25),('c','C',3,40);
 insert into private.map_passwords values('a','1234'),('b','5678'),('c','9012');
 insert into private.map_admins values('${event}','00000000-0000-0000-0000-000000000003');`);
 const login=async(n:number,anonymous=true)=>{await db.exec(`reset role; select set_config('test.uid','00000000-0000-0000-0000-00000000000${n}',false);select set_config('test.anonymous','${anonymous}',false);set role authenticated;`);};
 const rpc=async(sql:string)=>(await db.query<{v:any}>(`select ${sql} as v`)).rows[0].v;
 await login(1);
 assert.equal((await rpc(`public.map_register('${event}','   ')`)).error,'INVALID_NAME');
 assert.equal((await rpc(`public.map_register('10000000-0000-0000-0000-000000000099','一班')`)).error,'EVENT_CLOSED');
 const team=await rpc(`public.map_register('${event}','一班')`);assert.equal(team.total_points,0);assert.equal((await rpc(`public.map_register('${event}','再登録')`)).id,team.id);
 assert.equal((await rpc(`public.map_redeem('${team.id}','a','0000')`)).error,'INVALID_PASSWORD');
 assert.equal((await rpc(`public.map_redeem('${team.id}','a','1234')`)).total_points,10);
 for(let i=0;i<4;i++)assert.equal((await rpc(`public.map_redeem('${team.id}','a','1234')`)).total_points,10);
 assert.equal((await rpc(`public.map_redeem('${team.id}','b','5678')`)).total_points,35);
 assert.equal((await rpc(`public.map_redeem('${team.id}','c','9012')`)).total_points,75);
 assert.equal((await rpc(`public.map_my_team('${event}')`)).completed.length,3);
 await assert.rejects(db.exec(`update public.map_tasks set points=40`),/permission denied/);
 await assert.rejects(db.exec(`insert into public.map_completions values('${team.id}','a',now())`),/permission denied/);
 await assert.rejects(db.exec('select * from private.map_passwords'),/permission denied/);
 await assert.rejects(rpc(`public.map_admin_teams('${event}')`),/FORBIDDEN/);
 await login(2);assert.equal((await db.query('select * from public.map_teams')).rows.length,0);assert.equal((await db.query('select * from public.map_completions')).rows.length,0);
 await assert.rejects(rpc(`public.map_redeem('${team.id}','a','1234')`),/FORBIDDEN/);
 await assert.rejects(rpc(`public.map_reset('${team.id}')`),/FORBIDDEN/);
 const other=await rpc(`public.map_register('${event}','二班')`);
 for(let i=0;i<5;i++)assert.equal((await rpc(`public.map_redeem('${other.id}','a','0000')`)).error,'INVALID_PASSWORD');
 assert.equal((await rpc(`public.map_redeem('${other.id}','a','1234')`)).error,'RATE_LIMIT');
 await login(3,false);assert.equal((await rpc(`public.map_admin_teams('${event}')`)).length,2);
 await login(3,true);await assert.rejects(rpc(`public.map_admin_teams('${event}')`),/FORBIDDEN/);
 await login(1);assert.equal(await rpc(`public.map_reset('${team.id}')`),true);assert.equal((await rpc(`public.map_my_team('${event}')`)).total_points,0);
 await login(2);assert.equal((await rpc(`public.map_my_team('${event}')`)).id,other.id);
 await assert.rejects(rpc(`public.map_admin_reset('${event}')`),/FORBIDDEN/);
 await db.exec(`reset role; insert into private.map_events(id,name,join_hash) values('10000000-0000-0000-0000-000000000002','Other event','JOIN');`);
 await login(2);const kept=await rpc(`public.map_register('10000000-0000-0000-0000-000000000002','別開催')`);
 await login(3,true);await assert.rejects(rpc(`public.map_admin_reset('${event}')`),/FORBIDDEN/);
 await login(3,false);assert.equal(await rpc(`public.map_admin_reset('${event}')`),2);assert.deepEqual(await rpc(`public.map_admin_teams('${event}')`),[]);
 await login(1);assert.equal(await rpc(`public.map_my_team('${event}')`),null);await assert.rejects(rpc(`public.map_redeem('${team.id}','a','1234')`),/FORBIDDEN/);
 const restarted=await rpc(`public.map_register('${event}','新しい班')`);assert.notEqual(restarted.id,team.id);assert.equal(restarted.total_points,0);
 await login(2);assert.equal((await rpc(`public.map_my_team('10000000-0000-0000-0000-000000000002')`)).id,kept.id);
 await db.exec(`reset role;`);
 await db.exec(readFileSync(new URL('../migrations/004_public_admin.sql',import.meta.url),'utf8'));
 await db.exec(`select set_config('test.uid','',false);set role anon;`);
 const publicTeams=await rpc(`public.map_admin_teams('${event}')`);assert.equal(publicTeams.length,1);assert.equal(publicTeams[0].team_name,'新しい班');assert.equal('user_id' in publicTeams[0],false);
 await assert.rejects(db.exec('select * from private.map_passwords'),/permission denied/);
 await assert.rejects(db.exec('select * from public.map_teams'),/permission denied/);
 assert.equal(await rpc(`public.map_admin_reset('${event}')`),1);assert.deepEqual(await rpc(`public.map_admin_teams('${event}')`),[]);
 assert.equal((await rpc(`public.map_admin_teams('10000000-0000-0000-0000-000000000002')`)).length,1);
 await db.exec('reset role');
 await db.exec(readFileSync(new URL('../migrations/005_admin_password.sql',import.meta.url),'utf8'));
 await db.exec('set role anon');
 await assert.rejects(rpc(`public.map_admin_teams('${event}')`),/does not exist/);
 await assert.rejects(rpc(`public.map_admin_reset('${event}','0000')`),/INVALID_ADMIN_PASSWORD/);
 await assert.rejects(rpc(`public.map_admin_teams('${event}',null)`),/INVALID_ADMIN_PASSWORD/);
 await assert.rejects(rpc(`public.map_admin_teams('${event}','0000')`),/INVALID_ADMIN_PASSWORD/);
 await assert.rejects(rpc(`private.map_admin_teams_data('${event}')`),/permission denied/);
 const otherEvent='10000000-0000-0000-0000-000000000002';
 assert.equal((await rpc(`public.map_admin_teams('${otherEvent}','1111')`)).length,1);
 assert.equal(await rpc(`public.map_admin_reset('${otherEvent}','1111')`),1);
 assert.deepEqual(await rpc(`public.map_admin_teams('${otherEvent}','1111')`),[]);
 await db.exec('reset role');
 await db.exec(readFileSync(new URL('../migrations/006_admin_complete.sql',import.meta.url),'utf8'));
 await login(1);const manualTeam=await rpc(`public.map_register('${event}','運営採点')`);
 await db.exec(`reset role; select set_config('test.uid','',false);set role anon;`);
 await assert.rejects(rpc(`public.map_admin_complete('${event}','${manualTeam.id}','a','0000')`),/INVALID_ADMIN_PASSWORD/);
 await assert.rejects(rpc(`public.map_admin_complete('${otherEvent}','${manualTeam.id}','a','1111')`),/TEAM_NOT_FOUND/);
 await assert.rejects(rpc(`public.map_admin_complete('${event}','${manualTeam.id}','missing','1111')`),/INVALID_TASK/);
 assert.equal((await rpc(`public.map_admin_complete('${event}','${manualTeam.id}','a','1111')`)).total_points,10);
 for(let n=0;n<3;n++)assert.equal((await rpc(`public.map_admin_complete('${event}','${manualTeam.id}','a','1111')`)).total_points,10);
 assert.equal((await rpc(`public.map_admin_complete('${event}','${manualTeam.id}','b','1111')`)).total_points,35);
 assert.equal((await rpc(`public.map_admin_complete('${event}','${manualTeam.id}','c','1111')`)).total_points,75);
 await login(1);assert.equal((await rpc(`public.map_my_team('${event}')`)).completed.length,3);
 assert.equal((await rpc(`public.map_redeem('${manualTeam.id}','a','1234')`)).total_points,75);
 await rpc(`public.map_reset('${manualTeam.id}')`);assert.equal((await rpc(`public.map_my_team('${event}')`)).total_points,0);
 }finally{await db.close();}
});
